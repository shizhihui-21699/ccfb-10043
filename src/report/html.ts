export interface ViewerFinding {
  id: string;
  path: string;
  layer: number;
  visible: boolean;
  reason: string;
  deletedInLayer?: number;
  deletionReason?: string;
  ruleId: string;
  ruleName: string;
  category: string;
  severity: string;
  value: string;
  line?: number;
  context?: string;
  createdBy?: string;
  createdAt?: string;
  historyIndex?: number;
  fileSize: number;
}

export interface ViewerData {
  image: string;
  generatedAt: string;
  imageCreated?: string;
  stats: ScanReport['stats'];
  warnings: string[];
  findings: ViewerFinding[];
  layers: LayerSummary[];
  ghosts: GhostSummary[];
  history: HistorySummary[];
  configFindings: Array<{
    kind: string;
    key: string;
    ruleId: string;
    ruleName: string;
    category: string;
    severity: string;
    maskedValue: string;
    maskedSource: string;
  }>;
}

export function viewerData(report: ScanReport): ViewerData {
  const findings: ViewerFinding[] = report.findings.map((f: Finding) => ({
    id: f.id,
    path: f.path,
    layer: f.layer,
    visible: f.visible,
    reason: f.reason,
    ...(f.deletedInLayer !== undefined ? { deletedInLayer: f.deletedInLayer } : {}),
    ...(f.deletionReason ? { deletionReason: f.deletionReason } : {}),
    ruleId: f.ruleId,
    ruleName: f.ruleName,
    category: f.category,
    severity: f.severity,
    value: f.value,
    ...(f.line !== undefined ? { line: f.line } : {}),
    ...(f.context ? { context: f.context } : {}),
    ...(f.createdBy ? { createdBy: f.createdBy } : {}),
    ...(f.created ? { createdAt: f.created } : {}),
    ...(f.historyIndex !== undefined ? { historyIndex: f.historyIndex } : {}),
    fileSize: f.fileSize,
  }));
  return {
    image: report.image,
    generatedAt: report.generatedAt,
    ...(report.imageCreated ? { imageCreated: report.imageCreated } : {}),
    stats: report.stats,
    warnings: report.warnings,
    findings,
    layers: report.layerSummaries,
    ghosts: report.ghosts,
    history: report.history,
    configFindings: report.configFindings.map((c) => ({
      kind: c.kind,
      key: c.key,
      ruleId: c.ruleId,
      ruleName: c.ruleName,
      category: c.category,
      severity: c.severity,
      maskedValue: c.maskedValue,
      maskedSource: c.maskedSource,
    })),
  };
}

