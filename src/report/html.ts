export function renderTextReport(report: ScanReport, color = false): string {
  const c = (code: string) => (s: string) => (color ? `\x1b[${code}m${s}\x1b[0m` : s);
  const red = c('31');
  const yellow = c('33');
  const blue = c('36');
  const dim = c('2');
  const bold = c('1');

  const lines: string[] = [];
  lines.push(bold(`Image layer audit — ${report.image}`));
  lines.push(
    dim(
      `${report.stats.layers} layers · ${report.stats.scannedFiles} files scanned · ${formatBytes(
        report.stats.scannedBytes,
      )} · ${report.stats.durationMs}ms`,
    ),
  );
  lines.push('');

  const bySeverity = new Map<string, Finding[]>();
  for (const f of report.findings) {
    const list = bySeverity.get(f.severity) ?? [];
    list.push(f);
    bySeverity.set(f.severity, list);
  }

  if (report.findings.length === 0) {
    lines.push('No secrets found.');
  } else {
    for (const sev of ['critical', 'high', 'medium', 'low', 'info']) {
      const list = bySeverity.get(sev);
      if (!list || list.length === 0) continue;
      const paint = sev === 'critical' ? red : sev === 'high' ? yellow : blue;
      lines.push(paint(`${sev.toUpperCase()} (${list.length})`));
      for (const f of list) {
        const state = f.visible ? 'in image' : f.reason === 'overwritten' ? 'overwritten' : 'deleted';
        lines.push(`  ${f.path}  ${dim(`[layer ${f.layer}, ${state}]`)}`);
        lines.push(`    ${f.ruleName}: ${f.value}`);
        if (f.createdBy) lines.push(`    ${dim(`introduced by: ${f.createdBy}`)}`);
      }
      lines.push('');
    }
  }

  const ghostSecrets = report.findings.filter((f: Finding) => !f.visible);
  if (ghostSecrets.length > 0) {
    lines.push(blue(`Hidden-layer secrets: ${ghostSecrets.length}`));
    for (const f of ghostSecrets) {
      lines.push(
        `  ${f.path} ${dim(`(layer ${f.layer}, hidden by layer ${f.deletedInLayer ?? '?'}${f.deletionReason ? ` ${f.deletionReason}` : ''})`)}`,
      );
    }
    lines.push('');
  }

  if (report.configFindings.length > 0) {
    lines.push(blue(`Secrets in image metadata: ${report.configFindings.length}`));
    lines.push(dim('  ENV, labels and history ship with the image; deleting files does not remove them.'));
    for (const c of report.configFindings) {
      const where = c.kind === 'env' ? `ENV ${c.key}` : c.kind === 'label' ? `LABEL ${c.key}` : `history[${c.key}]`;
      const paint = c.severity === 'critical' ? red : c.severity === 'high' ? yellow : blue;
      lines.push(`  ${paint(c.severity)} ${where}: ${c.ruleName} ${c.maskedValue}`);
    }
    lines.push('');
  }

  if (report.ghosts.length > 0) {
    lines.push(`Files present in layers but absent from the final filesystem: ${report.ghosts.length}`);
    for (const g of report.ghosts.slice(0, 50)) {
      const where =
        g.deletionLayer !== undefined
          ? `hidden by layer ${g.deletionLayer}${g.deletionReason ? ` (${g.deletionReason})` : ''}`
          : `newest copy in layer ${g.layer}`;
      lines.push(`  ${g.path} ${dim(`(${where})`)}`);
    }
    if (report.ghosts.length > 50) lines.push(dim(`  … ${report.ghosts.length - 50} more`));
    lines.push('');
  }

  if (report.warnings.length > 0) {
    lines.push(yellow('Warnings:'));
    for (const w of report.warnings) lines.push(`  - ${w}`);
  }

  return lines.join('\n');
}
